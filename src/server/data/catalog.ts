const catalogMap = new Map<string, CatalogItem>(
  SYNTHETIC_CATALOG.map((item) => [item.sku, item])
);

// Register aliases in map
for (const [aliasSku, targetSku] of Object.entries(SKU_ALIASES)) {
  const targetItem = catalogMap.get(targetSku);
  if (targetItem) {
    catalogMap.set(aliasSku, {
      ...targetItem,
      sku: aliasSku,
    });
  }
}

/**
 * Returns all catalog items.
 */
export function getCatalogItems(): CatalogItem[] {
  return [...SYNTHETIC_CATALOG];
}

/**
 * Retrieves a catalog item by its unique SKU or alias.
 */
export function getCatalogItemBySku(sku: string): CatalogItem | undefined {
  return catalogMap.get(sku);
}
